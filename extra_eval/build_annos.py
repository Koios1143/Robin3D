#!/usr/bin/env python3
"""Set up ``annotations/`` and ``scripts/extra_eval_config.py`` for ``run_extra_eval.sh``.

* Real-3DQA (``debiased_test`` and ``rotation_{0,90,180,270}``) -> Robin3D's SQA3D val
  format as ``annotations/real3dqa_<split>.json``: prompt =
  ``<situation> <question> Answer the question using a word or a phrase.`` (the exact
  suffix of Robin3D's released ``sqa3d_test.json``), ``sqa_type`` = the question's first
  word (What/Is/How/Can/Which/other = 0..5), ``qid`` = Real-3DQA ``question_id``. The
  rotation splits differ only in the situation text, so the scene input is the same as
  for SQA3D.
* Beacon3D ScanNet -> ``annotations/beacon3d_scannet_{grounding,qa}.json``. Grounding uses
  the single template of Robin3D's released ``scanrefer_mask3d_val.json``; QA uses the
  ScanQA suffix above. ``qid`` = the item's index in Beacon3D's ``scannet_<task>.json``.
* Writes ``scripts/extra_eval_config.py`` = ``scripts/config.py`` with its data paths
  pointed at the released Google Drive files (``--robin3d_data``) and the Vicuna path,
  plus one ``val_file_dict`` entry per new set and ``check_scanrefer`` (= ``scanrefer``).
  Every entry uses the same Mask3D / Uni3D / DINOv2 ScanNet val features as Robin3D's own ``scanqa`` and ``sqa3d_test`` entries.
"""

import argparse
import json
import os
import re

REAL3DQA_SPLITS = ["debiased_test", "rotation_0", "rotation_90", "rotation_180", "rotation_270"]
QA_SUFFIX = " Answer the question using a word or a phrase."
GROUNDING_PROMPT = ('According to the given description, "{}" please provide the ID of the object '
                    'that has the closest match to this description.')
SQA_TYPE = {"what": 0, "is": 1, "how": 2, "can": 3, "which": 4}
ANNO_SUBDIR = "chat3d-anno/mask3d150sort-uni3d-dinov2Giant-iou50-oneprompt"
FEAT_SUBDIR = "mask3d_uni3d_dinov2/mask3d150sort_uni3d_dinov2G"
GT_ATTR = "chat3d-anno/scannet/scannet_val_attributes.pt"


def convert_real3dqa(real3dqa_dir, anno_dir):
    names = []
    for split in REAL3DQA_SPLITS:
        out = []
        for line in open(os.path.join(real3dqa_dir, f"{split}.jsonl")):
            x = json.loads(line)
            q = x["question"].strip()
            out.append({
                "scene_id": x["scene_id"],
                "obj_id": 0,
                "prompt": f'{x["situation"].strip()} {q}{QA_SUFFIX}',
                "ref_captions": [x["answer"]],
                "sqa_type": SQA_TYPE.get(q.split(" ")[0].lower(), 5),
                "qid": str(x["question_id"]),
                "question_type": x["question_type"],
            })
        json.dump(out, open(os.path.join(anno_dir, f"real3dqa_{split}.json"), "w"), indent=1)
        print(f"real3dqa_{split}: {len(out)}")
        names.append(f"real3dqa_{split}")
    return names


def convert_beacon3d(beacon_root, anno_dir):
    bdir = os.path.join(beacon_root, "data", "scannet")
    grounding = [{"scene_id": x["scan_id"], "obj_id": 0, "qid": i, "ref_captions": [],
                  "prompt": GROUNDING_PROMPT.format(x["utterance"].strip())}
                 for i, x in enumerate(json.load(open(os.path.join(bdir, "scannet_grounding.json"))))]
    qa = [{"scene_id": x["scene_id"], "obj_id": 0, "qid": i, "ref_captions": x["answers"],
           "prompt": x["question"].strip() + QA_SUFFIX}
          for i, x in enumerate(json.load(open(os.path.join(bdir, "scannet_qa.json"))))]
    for task, rows in [("grounding", grounding), ("qa", qa)]:
        json.dump(rows, open(os.path.join(anno_dir, f"beacon3d_scannet_{task}.json"), "w"), indent=1)
        print(f"beacon3d_scannet_{task}: {len(rows)}")
    return ["beacon3d_scannet_grounding", "beacon3d_scannet_qa"]


def write_config(config_out, robin3d_data, llama, anno_dir, names):
    src = open("scripts/config.py").read()
    subs = {
        "scene_val_attr_file": os.path.join(robin3d_data, GT_ATTR),
        "scene_train_attr_file": os.path.join(robin3d_data, GT_ATTR),  # unused at eval time
        "anno_root": os.path.join(robin3d_data, ANNO_SUBDIR),
        "pred_root": os.path.join(robin3d_data, FEAT_SUBDIR),
    }
    for var, val in subs.items():
        src, n = re.subn(rf"^{var} = .*$", f"{var} = {val!r}", src, count=1, flags=re.M)
        assert n == 1, var
    src, n = re.subn(r'llama_model_path=".*?"', f"llama_model_path={llama!r}", src, count=1)
    assert n == 1
    lines = ["\n\n# ---- extra benchmarks (generated by extra_eval/build_annos.py) ----"]
    for name in names:
        anno = os.path.abspath(os.path.join(anno_dir, f"{name}.json"))
        lines.append(f"val_file_dict[{name!r}] = val_file_dict['sqa3d_test'][:5] + [{anno!r}, scene_val_attr_file]")
    # Robin3D's own ScanRefer val set under another name, so train.py skips its scorer (which
    # reads files from the authors' machine); extra_eval/score.py scores it and compares it
    # with the authors' released predictions to check the inference setup.
    lines.append("val_file_dict['check_scanrefer'] = val_file_dict['scanrefer']")
    open(config_out, "w").write(src + "\n".join(lines) + "\n")
    print(f"config -> {config_out}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--robin3d_data", required=True, help="Robin3D Google Drive download (extra_eval/download.sh)")
    ap.add_argument("--real3dqa_dir", required=True, help="dir with Real-3DQA <split>.jsonl")
    ap.add_argument("--beacon_root", default="extra_eval/beacon3d/Beacon3D")
    ap.add_argument("--llama", required=True, help="Vicuna-7B v1.5 path or HF id")
    ap.add_argument("--anno_dir", default="annotations")
    ap.add_argument("--config_out", default="scripts/extra_eval_config.py")
    args = ap.parse_args()
    os.makedirs(args.anno_dir, exist_ok=True)
    names = convert_real3dqa(args.real3dqa_dir, args.anno_dir)
    names += convert_beacon3d(args.beacon_root, args.anno_dir)
    write_config(args.config_out, os.path.abspath(args.robin3d_data), args.llama, args.anno_dir, names)


if __name__ == "__main__":
    main()
